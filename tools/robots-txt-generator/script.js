(function () {
  "use strict";
  var sitemapUrl = document.getElementById("sitemapUrl");
  var disallowPaths = document.getElementById("disallowPaths");
  var customRules = document.getElementById("customRules");
  var generateBtn = document.getElementById("generateBtn");
  var output = document.getElementById("txtOutput");
  var copyBtn = document.getElementById("copyBtn");
  var downloadBtn = document.getElementById("downloadBtn");

  function generate() {
    var lines = ["# Robots.txt generated by OmniTools", ""];
    lines.push("User-agent: *");
    var paths = disallowPaths.value.split("\n").map(function (l) { return l.trim(); }).filter(Boolean);
    if (paths.length === 0) {
      lines.push("Disallow:");
    } else {
      paths.forEach(function (p) { lines.push("Disallow: " + p); });
    }
    lines.push("");
    if (sitemapUrl.value.trim()) {
      lines.push("Sitemap: " + sitemapUrl.value.trim());
      lines.push("");
    }
    var custom = customRules.value.trim();
    if (custom) {
      lines.push("# Custom rules");
      lines.push(custom);
      lines.push("");
    }
    output.textContent = lines.join("\n");
  }

  generateBtn.addEventListener("click", generate);

  copyBtn.addEventListener("click", function () {
    var text = output.textContent;
    window.OmniTools.copyText(text).then(function () {
      window.OmniTools.showToast("Copied to clipboard.", "success");
    });
  });

  downloadBtn.addEventListener("click", function () {
    var blob = new Blob([output.textContent], { type: "text/plain;charset=utf-8;" });
    var url = URL.createObjectURL(blob);
    var a = document.createElement("a");
    a.href = url; a.download = "robots.txt"; a.click();
    URL.revokeObjectURL(url);
  });
})();
